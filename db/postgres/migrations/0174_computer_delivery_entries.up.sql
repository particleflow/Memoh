-- 0174_computer_delivery_entries
-- Normalize the existing operation ledger without changing delivery identities.
-- Stop old writers before upgrade. All DDL/backfill/guards commit atomically.
CREATE TABLE IF NOT EXISTS public.computer_delivery_entries (
    team_id UUID NOT NULL DEFAULT public.memoh_current_team_id(),
    operation_id UUID NOT NULL,
    delivery_id TEXT COLLATE "C" NOT NULL CHECK (delivery_id ~ '^[a-zA-Z0-9_-]{1,128}$'),
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    version INTEGER NOT NULL CHECK (version BETWEEN 1 AND 4),
    entry JSONB NOT NULL CHECK (jsonb_typeof(entry) = 'object'),
    PRIMARY KEY (team_id, operation_id, delivery_id),
    FOREIGN KEY (team_id, operation_id) REFERENCES public.computer_operations(team_id,id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS computer_delivery_entries_page ON public.computer_delivery_entries(team_id,operation_id,ordinal);

-- Migration owns the table locks; restore RLS before the transaction commits.
-- Do not accidentally copy only the current team's history under FORCE RLS.
ALTER TABLE public.computer_operations DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.computer_delivery_entries DISABLE ROW LEVEL SECURITY;
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM public.computer_operations
        WHERE details ? 'delivery_ledger'
        AND details->'delivery_ledger' <> '{"version":5,"storage":"rows"}'::jsonb
        AND (COALESCE(details->'delivery_ledger'->>'version','') NOT IN ('1','2','3','4')
             OR jsonb_typeof(details->'delivery_ledger'->'entries') IS DISTINCT FROM 'object')) THEN
        RAISE EXCEPTION 'unrecognized computer delivery ledger; history retained' USING ERRCODE='23514';
    END IF;
END $$;
INSERT INTO public.computer_delivery_entries(team_id,operation_id,delivery_id,version,entry)
SELECT o.team_id,o.id,e.key,(o.details->'delivery_ledger'->>'version')::integer,e.value
FROM public.computer_operations o
CROSS JOIN LATERAL jsonb_each(o.details->'delivery_ledger'->'entries') e
WHERE o.details->'delivery_ledger'->>'version' IN ('1','2','3','4');
UPDATE public.computer_operations
SET details=jsonb_set(details,'{delivery_ledger}','{"version":5,"storage":"rows"}'::jsonb)
WHERE details->'delivery_ledger'->>'version' IN ('1','2','3','4');

ALTER TABLE public.computer_operations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.computer_operations FORCE ROW LEVEL SECURITY;
ALTER TABLE public.computer_delivery_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.computer_delivery_entries FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS computer_delivery_entries_team ON public.computer_delivery_entries;
CREATE POLICY computer_delivery_entries_team ON public.computer_delivery_entries
    USING (team_id=public.memoh_current_team_id())
    WITH CHECK (team_id=public.memoh_current_team_id());

CREATE OR REPLACE FUNCTION public.memoh_guard_computer_delivery() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF (OLD.details ? 'delivery_ledger' OR NEW.details ? 'delivery_ledger')
       AND (NEW.details->'delivery_ledger' IS DISTINCT FROM '{"version":5,"storage":"rows"}'::jsonb) THEN
        RAISE EXCEPTION 'computer delivery row layout requires current writer' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
