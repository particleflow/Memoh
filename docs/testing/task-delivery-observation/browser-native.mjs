import fs from 'node:fs'
import crypto from 'node:crypto'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const root=process.env.EVIDENCE_DIR
assert(root && process.env.APP_URL && process.env.TOKEN_FILE && process.env.FIXTURE_FILE)
const appURL=process.env.APP_URL.replace(/\/$/,'')
const fixture=JSON.parse(fs.readFileSync(process.env.FIXTURE_FILE,'utf8'))
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox']})
try {
 const context=await browser.newContext({viewport:{width:1200,height:1000}})
 await context.addInitScript(token=>{localStorage.setItem('token',token);localStorage.setItem('language','en')},fs.readFileSync(process.env.TOKEN_FILE,'utf8').trim())
 const page=await context.newPage();page.setDefaultTimeout(20000)
 const errors=[],requests=[]
 page.on('pageerror',e=>errors.push(e.message))
 page.on('response',r=>{if(new URL(r.url()).pathname.endsWith('/deliveries'))requests.push({status:r.status(),method:r.request().method(),continued:!!new URL(r.url()).searchParams.get('after')})})
 await page.goto(`${appURL}/bot/${fixture.bot}`)
 await page.getByText('Task file observation synthetic',{exact:true}).first().click()
 await page.getByRole('button',{name:'Tasks',exact:true}).click()
 await page.getByRole('button').filter({hasText:fixture.operation.slice(0,8)}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByText('result-17',{exact:true}).waitFor()
 assert(await dialog.getByText('result-16',{exact:true}).count())
 assert((await dialog.innerText()).includes('Delivery pending'))
 assert((await dialog.innerText()).includes('Delivery failed'))
 assert((await dialog.innerText()).includes('Business completion remains unverified.'))
 await dialog.getByText('synthetic-picture',{exact:true}).first().waitFor()
 assert.equal(await dialog.locator('a[download]').count(),17)
 const mediaRequests=[]
 page.on('response',r=>{if(new URL(r.url()).pathname.includes('/media/'))mediaRequests.push({status:r.status(),method:r.request().method()})})
 const downloaded=page.waitForEvent('download')
 await dialog.locator('a[download]').first().click()
 const download=await downloaded
 const bytes=fs.readFileSync(await download.path())
 assert.equal(bytes.length,fixture.asset.size_bytes)
 assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),fixture.asset.content_hash)
 assert.equal(download.suggestedFilename(),'result-00.txt')
 console.log('PASS native browser download: full bytes/hash match the original NAS media fixture')
 assert(requests.some(r=>r.status===200 && !r.continued) && requests.some(r=>r.status===200 && r.continued))
 await page.screenshot({path:`${root}/native-browser-results.png`})
 await dialog.locator('img[alt="synthetic-picture"]').click()
 const lightbox=dialog.locator('[data-keyboard-scope="mediaLightbox"]')
 await lightbox.waitFor()
 await lightbox.locator('img').evaluate(img=>img.decode())
 assert.equal(await lightbox.locator('img').evaluate(img=>img.naturalWidth),1)
 await page.screenshot({path:`${root}/native-browser-image.png`})
 await lightbox.getByRole('button',{name:'Close',exact:true}).click()
 await lightbox.waitFor({state:'hidden'})
 console.log('PASS original media lightbox opens the native uploaded PNG inside the task host')
 console.log('PASS actual Web + JWT server + PG: all 19 seeded records automatically read; pending/failed distinct; 17 native download links only for committed references')
 await context.setOffline(true)
 await dialog.getByText('Network connection failed. Check your connection and try again.',{exact:true}).first().waitFor()
 assert.equal(await dialog.getByText('result-00',{exact:true}).count(),0)
 await context.setOffline(false)
 await dialog.getByText('result-17',{exact:true}).waitFor()
 console.log('PASS real browser offline -> same selected detail and file records automatically recover, no task dispatch')
 const route=`**/tasks/computer_operation/${fixture.operation}/deliveries*`
 await page.route(route,r=>r.fulfill({status:404,contentType:'application/problem+json',body:JSON.stringify({code:'http.not_found',status:404})}))
 await dialog.getByText('This server does not support task file observation yet.',{exact:true}).waitFor()
 const failedReads=requests.filter(r=>r.status===404).length
 await page.waitForTimeout(5500)
 assert.equal(requests.filter(r=>r.status===404).length,failedReads)
 await page.screenshot({path:`${root}/native-browser-unsupported.png`})
 await page.unroute(route)
 await dialog.getByRole('button',{name:'Reload view',exact:true}).click()
 await dialog.getByText('result-17',{exact:true}).waitFor()
 console.log('PASS synthetic old-route 404 is unavailable, does not poll; explicit reload recovers against real backend')
 await dialog.locator('button[title="result-00"]').click()
 await dialog.waitFor({state:'hidden'})
 await page.getByText('Preview not available for this file type',{exact:true}).waitFor()
 await page.screenshot({path:`${root}/native-browser-open.png`})
 console.log('PASS attachment uses existing asset dock and dismisses task dialog; source has no original filename, native fallback offers download')
 const anonymous=await context.request.get(`${appURL}/api/bots/${fixture.bot}/media/${fixture.asset.content_hash}`)
 assert.equal(anonymous.status(),401)
 assert(mediaRequests.some(r=>r.status===200 && r.method==='GET'))
 assert.equal(errors.length,0)
 fs.writeFileSync(`${root}/native-browser-proof.json`,JSON.stringify({realServer:true,realPostgres:true,seededMetadata:true,realMediaUpload:true,taskDispatches:0,modelCalls:0,nativeDownload:true,nativePreviewHost:true,nativeImageLightbox:true,byteCount:bytes.length,sha256Matches:true,anonymous:401,mediaRequests,pageErrors:errors,deliveryRequests:requests,offlineRecovery:true,synthetic404:true},null,2)+'\n')
} finally {await browser.close()}
