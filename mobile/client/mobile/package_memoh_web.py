"""Package only the verified direct Memoh client into the existing Harmony App."""
import hashlib
import json
from pathlib import Path
import sys

from build_memoh_web import ROOT, BASE, DIST, inputs, verify_modules, sha
sys.path.insert(0, str(ROOT / 'tools'))
from artifact_paths import checked

RAW = ROOT / 'mobile/harmony/app/entry/src/main/resources/rawfile/client-web'
THEME = ROOT / 'contracts/ui_theme.json'
THEME_RESOURCE = RAW.parent / 'ui-theme.json'
MANIFEST = ROOT / 'mobile/harmony/app/entry/src/main/ets/common/WebResourceManifest.ets'
CONFIG = ROOT / 'mobile/harmony/app/entry/src/main/ets/common/MemohClientConfig.ets'
SERVICE_URL = CONFIG.with_name('ServiceUrl.ets')
SERVICE_SOURCE = ROOT / 'mobile/memoh/harmony-service-url.ts'
MIMES = {'.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.txt': 'text/plain',
         '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.wasm': 'application/wasm', '.woff': 'font/woff', '.woff2': 'font/woff2', '.ttf': 'font/ttf',
         '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon', '.gif': 'image/gif'}

def validate_build():
    build = json.loads((BASE / 'build.json').read_text())
    assert build['exitCode'] == 0 and build['inputs'] == inputs(), 'Build the current Memoh client first'
    assert build['platform'] == 'harmony', 'Package the runtime-configured Harmony build'
    verify_modules(build['modules'])
    actual = {p.relative_to(DIST).as_posix(): sha(p) for p in DIST.rglob('*') if p.is_file()}
    assert actual == build['resources'], 'Built resources changed'
    return build

def verify_current_package():
    validate_build()
    package = json.loads((BASE / 'resource-package.json').read_text())
    assert package['buildSHA256'] == sha(BASE / 'build.json')
    assert package['packageScriptSHA256'] == sha(Path(__file__))
    assert package['manifestSHA256'] == sha(MANIFEST) and package['configSHA256'] == sha(CONFIG)
    assert package['serviceUrlSHA256'] == sha(SERVICE_URL)
    assert SERVICE_URL.read_text() == native_service_url(), 'Native URL validator drift'
    assert sha(checked(THEME_RESOURCE)) == sha(checked(THEME)), 'Packaged native theme drift'
    actual = {p.relative_to(RAW).as_posix(): sha(p) for p in RAW.rglob('*') if p.is_file()}
    assert actual == package['resources'], 'Packaged client resource drift'
    return package

def package_theme():
    checked(THEME_RESOURCE.parent).mkdir(parents=True, exist_ok=True)
    checked(THEME_RESOURCE).write_bytes(checked(THEME).read_bytes())

def native_service_url():
    source = checked(SERVICE_SOURCE).read_text()
    assert source.count('new URL(') == 2, 'Review the two platform URL parser seams'
    return ('// Generated from mobile/memoh/harmony-service-url.ts.\n'
            "import { url } from '@kit.ArkTS';\n" + source.replace('new URL(', 'url.URL.parseURL('))


def main():
    build = validate_build()
    package_theme()
    previous_path = BASE / 'resource-package.json'
    previous = json.loads(previous_path.read_text()) if previous_path.exists() else {'resources': {}}
    files = build['resources']
    existing = {p.relative_to(RAW).as_posix(): sha(p) for p in RAW.rglob('*') if p.is_file()} if RAW.exists() else {}
    assert all(name in files or previous['resources'].get(name) == digest for name, digest in existing.items()), 'Unknown packaged file'
    records = {}
    checked(RAW).mkdir(parents=True, exist_ok=True)
    for name, digest in files.items():
        target = checked(RAW / name)
        assert target.resolve().is_relative_to(RAW.resolve())
        mime = MIMES[Path(name).suffix]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((DIST / name).read_bytes())
        assert sha(target) == digest
        records[name] = {'mime': mime, 'bytes': target.stat().st_size}
    for name in existing.keys() - files.keys():
        target = checked(RAW / name)
        assert sha(target) == previous['resources'][name]
        target.unlink()
    MANIFEST.write_text('// Generated by mobile/package_memoh_web.py.\nexport interface PackagedWebResource { mime: string; bytes: number; }\nexport const WEB_RESOURCES: Record<string, PackagedWebResource> = ' + json.dumps(records, indent=2) + ';\n', encoding='utf-8')
    # Preserve the reviewed runtime configuration module; never bake an endpoint.
    checked(SERVICE_URL).write_text(native_service_url(), encoding='utf-8')
    report = {'buildSHA256': sha(BASE / 'build.json'), 'packageScriptSHA256': sha(Path(__file__)),
              'resources': files, 'manifestSHA256': sha(MANIFEST), 'configSHA256': sha(CONFIG),
              'serviceUrlSHA256': sha(SERVICE_URL),
              'runtime': 'NOT_EXECUTED'}
    previous_path.write_text(json.dumps(report, indent=2) + '\n')
    verify_current_package()
    print(json.dumps({'resources': len(files), 'directMemoh': True, 'nativeRuntime': 'NOT_EXECUTED'}))

if __name__ == '__main__':
    main()
